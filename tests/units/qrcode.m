static void expect(BOOL ok, NSString *what) { if (!ok) { fprintf(stderr, "FAIL %s\n", what.UTF8String); fails++; } }

static void same(NSString *text, NSArray *rows, NSString *what) {
    SFQRCode *c = [SFQRCode codeForText:text ecc:SFQRECCMedium];
    expect(c && c.size == (NSInteger)rows.count, [NSString stringWithFormat:@"%@: size %ld", what, (long)c.size]);
    for (NSInteger y = 0; c && y < c.size && y < (NSInteger)rows.count; y++)
        for (NSInteger x = 0; x < c.size; x++)
            if ([c darkAtX:x y:y] != ([rows[y] characterAtIndex:x] == '1')) { expect(NO, [NSString stringWithFormat:@"%@: module %ld,%ld", what, (long)x, (long)y]); return; }
}

